# Writes src/shared/metrics.ts: advance widths and side bearings of the bundled fonts, so the
# widgets can size their reference layout from real text widths instead of guesses.
#
#   py scripts/metrics.py      (needs fontTools: py -m pip install fonttools)
#
# Values are in 1/1000 em. Kerning is left out: it only ever makes text a little narrower.
import json, os, re
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHARS = "".join(chr(c) for c in range(32, 127)) + "".join(chr(c) for c in range(160, 256)) + "–—‘’“”…·°•€"


def ident(path):
    name = os.path.splitext(os.path.basename(path))[0]
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def main():
    man = json.load(open(os.path.join(ROOT, "vitrine.json"), encoding="utf-8"))
    out = [
        "// Generated by scripts/metrics.py from the bundled fonts: do not edit by hand.",
        "// Per font: cap height, x height and, for each character of `chars`, the advance width",
        "// and the left/right side bearings, all in 1/1000 em.",
        "",
        "export interface FontData {",
        "  cap: number;",
        "  x: number;",
        "  chars: string;",
        "  adv: number[];",
        "  lsb: number[];",
        "  rsb: number[];",
        "}",
        "",
    ]
    for f in man["fonts"]:
        if not f.lower().endswith((".ttf", ".otf")):
            continue
        t = TTFont(os.path.join(ROOT, f))
        upm = t["head"].unitsPerEm
        cmap = t.getBestCmap()
        hmtx = t["hmtx"]
        glyphs = t.getGlyphSet()
        k = 1000 / upm
        chars, adv, lsb, rsb = "", [], [], []
        for ch in CHARS:
            g = cmap.get(ord(ch))
            if g is None:
                continue
            a = hmtx[g][0]
            pen = BoundsPen(glyphs)
            glyphs[g].draw(pen)
            if pen.bounds:
                l, r = pen.bounds[0], a - pen.bounds[2]
            else:
                l, r = 0, 0
            chars += ch
            adv.append(round(a * k))
            lsb.append(round(l * k))
            rsb.append(round(r * k))
        os2 = t["OS/2"]
        out += [
            f"export const {ident(f)}: FontData = {{",
            f"  cap: {round(getattr(os2, 'sCapHeight', 0) * k or 700)},",
            f"  x: {round(getattr(os2, 'sxHeight', 0) * k or 500)},",
            f"  chars: {json.dumps(chars, ensure_ascii=False)},",
            f"  adv: [{', '.join(map(str, adv))}],",
            f"  lsb: [{', '.join(map(str, lsb))}],",
            f"  rsb: [{', '.join(map(str, rsb))}],",
            "};",
            "",
        ]
    dest = os.path.join(ROOT, "src", "shared", "metrics.ts")
    open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote", os.path.relpath(dest, ROOT))


if __name__ == "__main__":
    main()
